#!/usr/bin/env node
// Writes backend/src/data/releaseInfo.ts from docs/CHANGELOG.md: the notes of the
// release this build is, and the agent version that was official when it was cut.
// The backend image is built from backend/ alone, so the changelog itself is not
// in it; the About dialog (GET /api/about) reads this module instead.
//
//   node scripts/generate-release-info.mjs            write the file
//   node scripts/generate-release-info.mjs --check    exit 1 when the file is stale
//   node scripts/generate-release-info.mjs --print --changelog <path> --version <x.y.z>
//                                                     print the JSON, write nothing
//
// Run it in every release PR after the changelog is written. A backend test
// (src/data/__tests__/releaseInfo.test.ts) fails when the committed file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(root, 'backend/src/data/releaseInfo.ts');

const PLATFORM_HEADING = /^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})\s*$/;
const AGENT_HEADING = /^## Agent \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})\s*$/;

/** The first section whose heading matches: its version, date and body up to the next `## ` line. */
function firstSection(lines, heading) {
  const start = lines.findIndex((line) => heading.test(line));
  if (start < 0) return null;
  const [, version, date] = lines[start].match(heading);
  let end = lines.findIndex((line, i) => i > start && line.startsWith('## '));
  if (end < 0) end = lines.length;
  return { version, date, notes: lines.slice(start + 1, end).join('\n').trim() };
}

/** The bold lead-in of the first paragraph ("**Title.** ...") without its final period. */
function titleOf(notes) {
  const match = notes.match(/^\*\*(.+?)\*\*/);
  return match ? match[1].replace(/\.$/, '').trim() : '';
}

export function buildReleaseInfo(changelog, packageVersion) {
  const lines = changelog.split(/\r?\n/);
  const platform = firstSection(lines, PLATFORM_HEADING);
  if (!platform) throw new Error('no "## [x.y.z] - date" release heading in the changelog');
  if (platform.version !== packageVersion) {
    throw new Error(`changelog ${platform.version} does not match package.json ${packageVersion}`);
  }
  return { ...platform, title: titleOf(platform.notes), agent: firstSection(lines, AGENT_HEADING) };
}

function render(info) {
  return `// Generated by scripts/generate-release-info.mjs from docs/CHANGELOG.md. Do not edit.

export interface ReleaseSection {
  version: string;
  /** Release date, YYYY-MM-DD. */
  date: string;
  /** Markdown of the changelog section, without its heading line. */
  notes: string;
}

export interface ReleaseInfo extends ReleaseSection {
  /** Bold lead-in of the release summary, or '' when there is none. */
  title: string;
  /** The agent release that was the newest when this platform release was cut. */
  agent: ReleaseSection | null;
}

export const RELEASE_INFO: ReleaseInfo = ${JSON.stringify(info, null, 2)};
`;
}

function option(args, name) {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

function main(args) {
  const changelogPath = option(args, '--changelog') ?? path.join(root, 'docs/CHANGELOG.md');
  const version =
    option(args, '--version') ??
    JSON.parse(fs.readFileSync(path.join(root, 'backend/package.json'), 'utf8')).version;
  const info = buildReleaseInfo(fs.readFileSync(changelogPath, 'utf8'), version);

  if (args.includes('--print')) {
    process.stdout.write(JSON.stringify(info));
    return;
  }
  const wanted = render(info);
  if (args.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== wanted) {
      throw new Error('backend/src/data/releaseInfo.ts is stale: run node scripts/generate-release-info.mjs');
    }
    return;
  }
  fs.writeFileSync(OUTPUT, wanted);
  console.log(`Wrote ${path.relative(root, OUTPUT)} (${info.version}, agent ${info.agent?.version ?? 'none'})`);
}

try {
  main(process.argv.slice(2));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
