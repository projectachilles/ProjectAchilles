#!/usr/bin/env bash
# Appliance build, last step: seal the image so nothing in it identifies or
# authenticates one install (spec 6.3). build/check-sealed.sh asserts the
# result offline. Runs as root in the Packer build VM (sudo -E).
#
# Packer's shutdown_command (`sudo shutdown -P now`) still needs the build
# user's NOPASSWD rule, so the steps that take sudo away run at shutdown:
# this script starts a transient unit (lives in /run, gone after power-off)
# whose ExecStop removes the rule, locks the build user and drops the final
# logs. PENDING exists from the start of this script until the very last
# step of that ExecStop: if any step fails (set -eu) or never runs, the
# marker stays and check-sealed (run by build-image.sh) fails the image.
set -euo pipefail

log() { echo "seal: $*"; }
die() { echo "seal: $*" >&2; exit 1; }

USER_NAME=achilles
FINAL=/run/achilles-seal-final.sh
PENDING=/var/lib/projectachilles-seal-pending

id "$USER_NAME" >/dev/null || die "user $USER_NAME missing"
! id ubuntu >/dev/null 2>&1 || die "the cloud image's default user 'ubuntu' exists"

date -u >"$PENDING"

log "credentials"
passwd -l root
find /root /home \( -name authorized_keys -o -name authorized_keys2 \) -print -delete
# ssh_pwauth's drop-in; first boot writes its own (50-achilles.conf).
rm -f /etc/ssh/sshd_config.d/50-cloud-init.conf

log "identity"
rm -f /etc/ssh/ssh_host_*
# cloud-init clean before truncating: it may rewrite /etc/machine-id.
cloud-init clean --logs
[ -e /etc/cloud/cloud-init.disabled ] || die "cloud-init.disabled vanished"
: >/etc/machine-id
rm -f /var/lib/dbus/machine-id
ln -s /etc/machine-id /var/lib/dbus/machine-id
# Stopping saves the seed one last time; remove it after, and nothing saves
# it again at shutdown (the unit is already stopped).
systemctl stop systemd-random-seed.service
rm -f /var/lib/systemd/random-seed

log "docker identity"
# Per-daemon IDs, regenerated when missing at the first start on the
# customer's VM: engine-id, containerd's introspection UUID, BuildKit's
# worker ID and libnetwork's store (default network IDs).
systemctl stop docker.socket docker.service containerd.service
rm -f /var/lib/docker/engine-id \
	/var/lib/containerd/io.containerd.grpc.v1.introspection/uuid \
	/var/lib/docker/buildkit/containerd-overlayfs/workerid \
	/var/lib/docker/network/files/local-kv.db

log "build leftovers"
rm -rf /tmp/repo.bundle /tmp/rootfs /tmp/achilles-installer
apt-get clean
rm -rf /var/lib/apt/lists/*
# systemd-private-* belong to running services; tmpfiles empties /tmp at boot.
find /tmp /var/tmp -mindepth 1 -maxdepth 1 ! -name 'systemd-private-*' -exec rm -rf {} +
for home in /root /home/*; do
	rm -rf "$home/.bash_history" "$home/.lesshst" "$home/.viminfo" "$home/.wget-hsts" \
		"$home/.sudo_as_admin_successful" "$home/.cache" "$home/.docker" "$home/.gnupg"
done

log "logs"
# No more syslog files from here; journald keeps running (see FINAL).
systemctl stop rsyslog.service syslog.socket 2>/dev/null || true
journalctl --rotate
journalctl --vacuum-time=1s
find /var/log -type f ! -path '/var/log/journal/*' \
	\( -name '*.gz' -o -name '*.[0-9]' -o -name '*.old' \) -print -delete
find /var/log -path /var/log/journal -prune -o -type f -exec truncate -s 0 {} +

log "shutdown-time steps"
cat >"$FINAL" <<EOF
#!/bin/sh
# Generated by seal.sh; runs as ExecStop when Packer shuts the VM down.
set -eu
echo "seal-final: start"
rm -f /etc/sudoers.d/90-cloud-init-users
# Created again by the shutdown command's sudo.
rm -f /home/$USER_NAME/.sudo_as_admin_successful
passwd -l $USER_NAME
# Drop the build password's hash too: the field becomes just "!".
usermod -p '!' $USER_NAME
# shadow- (the tools' backup) still holds the old hash.
cp -p /etc/shadow /etc/shadow-
: >/etc/machine-id
rm -f /var/lib/systemd/random-seed
# Keep the journal (shutdown messages included) in /run from here on.
journalctl --relinquish-var
rm -rf /var/log/journal/*
find /var/log -path /var/log/journal -prune -o -type f -exec truncate -s 0 {} +
sync
fstrim -a
# Last step: everything above succeeded.
rm -f $PENDING
sync
echo "seal-final: done"
EOF
# /run is noexec: ExecStop runs it through /bin/sh.
chmod 0700 "$FINAL"
systemd-run --unit=achilles-seal-final --description="ProjectAchilles seal (shutdown)" \
	--property=Type=oneshot --property=RemainAfterExit=yes \
	--property=StandardOutput=journal+console --property=StandardError=journal+console \
	--property=TimeoutStopSec=10min --property=After=systemd-journald.service \
	--property=ExecStop="/bin/sh $FINAL" /bin/true
[ "$(systemctl is-active achilles-seal-final.service)" = active ] || die "achilles-seal-final not active"

log "trim"
sync
fstrim -av

# Assertions for what is final now.
[ -z "$(find /etc/ssh -name 'ssh_host_*')" ] || die "host keys left"
[ ! -s /etc/machine-id ] || die "/etc/machine-id not empty"
[ "$(readlink /var/lib/dbus/machine-id)" = /etc/machine-id ] || die "dbus machine-id is not a symlink"
[ -z "$(find /root /home -name 'authorized_keys*')" ] || die "authorized_keys left"
[ ! -e /var/lib/docker/engine-id ] || die "docker engine-id left"
[ -f "$PENDING" ] || die "$PENDING missing"
for u in achilles-firstboot achilles-issue achilles-growroot; do
	[ -f "/etc/systemd/system/$u.service" ] || die "$u.service file missing"
	[ "$(systemctl is-enabled "$u.service")" = enabled ] || die "$u.service not enabled"
done
log "done; the rest runs at shutdown"
